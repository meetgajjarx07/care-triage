def _preview(text, n=90):
    lines = [l for l in text.split("\n") if l.strip() and not l.lstrip().startswith("## ")]
    first = re.sub(r"^[^:\n]{0,40}: ", "", lines[0] if lines else text).strip("- ").strip()
    return first[:n] + ("…" if len(first) > n else "")


