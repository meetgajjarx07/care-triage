def _ece(rows, bins=5):
    r = rows.copy()
    r["bin"] = pd.qcut(r.conf, bins, labels=False, duplicates="drop")
    rel = r.groupby("bin").agg(mean_conf=("conf", "mean"), acc=("correct", "mean"), n=("conf", "size")).reset_index()
    return float((rel.n / rel.n.sum() * (rel.acc - rel.mean_conf).abs()).sum())


