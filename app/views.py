def _pick(df, key):
    ids = df["id"].tolist()
    cur = st.session_state.get("selected_id", ids[0])
    if cur not in ids:
        cur = ids[0]
    opt = [f"{r.id}  ·  {r.received_at:%d %b}  ·  {r.from_name}  ·  {r.subject}" for r in df.itertuples()]
    i = st.selectbox("Email", opt, index=ids.index(cur), key=key, label_visibility="collapsed")
    st.session_state["selected_id"] = i.split("  ·  ")[0]
    return st.session_state["selected_id"]


def _goto(page_name):
    st.switch_page(st.session_state["pages"][page_name])


def _qa_table(qa):
    rows = ""
    for c in qa["checks"]:
        st_ = tag("Pass", "ok") if c["ok"] else tag("Fail", "crit" if c["critical"] else "warn")
        crit = ' <span class="tag n">critical</span>' if c["critical"] else ""
        ev = f'<div class="ev">{c["evidence"]}</div>' if (not c["ok"] and c["evidence"]) else ""
        rows += f'<tr><td class="st">{st_}</td><td><div>{c["label"]}{crit}</div><div class="ev">{c["why"]}</div>{ev}</td></tr>'
    head = (f'<div class="t">Draft QA · score {qa["score"]} / 100 · {qa["passed"]} of {qa["total"]} checks'
            + (' · <b style="color:' + CRIT + '">critical fail</b>' if qa["critical_fail"] else "") + '</div>')
    h(f'<div class="panel {"crit" if qa["critical_fail"] else ("warn" if qa["score"] < 100 else "")}">{head}<table class="qa">{rows}</table></div>')


def _provenance(hits, model, secs, words, score_hint=True):
    seen = list(dict.fromkeys((x["doc"].replace(".md", ""), x["heading"]) for x in hits))
    chips = "".join(tag(f"{d} › {hd}", "chip") for d, hd in seen)
    return (f'<div class="prov"><span>Based on</span>{chips}<span style="margin-left:auto">Generated by <code class="mono">{model}</code>'
            f' · {secs:.1f} s · {words} words</span></div>')


def _draft_block(r, tr, run, key):
    """draft card with provenance banner, support highlighting toggle and QA scorecard"""
    S = tr.get("stages", {})
    C = S.get("check") or {}
    support = C.get("support", [])
    qa = C.get("qa")
    show = st.toggle("Highlight sentence support", value=True, key=f"hl_{key}", help=f"Each sentence of the draft is compared with the retrieved notes and the customer email by embedding similarity. Underlined green ≥ {SUPPORTED}, yellow ≥ {WEAK}, red below. Hover a sentence for the closest source.")
    body = highlight_draft(r.draft_reply, support) if (show and support) else r.draft_reply
    cls = "crit" if (qa and qa["critical_fail"]) else ("bad" if (qa and qa["score"] < 100) else "")
    h(f'<div class="mail draft {cls}"><div class="hd"><span class="s">Draft reply</span><span class="m">'
      + (qa_tag(qa["score"], qa["critical_fail"]) if qa else "") + '</span></div>'
      + _provenance(S.get("retrieve", {}).get("hits", []), run.get("draft_model", "llama3.2"), r.draft_seconds, len(r.draft_reply.split()))
      + f'<div class="bd">{body}</div></div>')
    if support:
        f = faithfulness(support)
        n_un = sum(1 for s in support if s["sim"] < WEAK); n_w = sum(1 for s in support if WEAK <= s["sim"] < SUPPORTED)
        h(f'<div class="note" style="margin-top:4px">{len(support)} sentences scored: {int(round(f*len(support)))} supported, {n_w} weak, {n_un} unsupported. '
          f'Similarity is a soft signal; the lexical check below is the hard one.</div>')
    if qa:
        st.write("")
        _qa_table(qa)


def _review_block(r, status):
    """approve / edit / discard + correction, written to out/reviews.jsonl"""
    section("Review", "decisions are appended to out/reviews.jsonl")
    c1, c2, c3 = st.columns(3)
    if c1.button("Approve draft", key=f"ap_{r.id}", type="primary", disabled=r.route != "draft_reply", width="stretch"):
        add_review(id=r.id, action="approve"); flash(f"{r.id} approved as written"); st.rerun()
    edit = c2.toggle("Edit then approve", key=f"ed_{r.id}", disabled=r.route != "draft_reply")
    if c3.button("Discard draft", key=f"di_{r.id}", disabled=r.route != "draft_reply", width="stretch"):
        add_review(id=r.id, action="discard", reason=st.session_state.get(f"why_{r.id}", "")); flash(f"{r.id} draft discarded", ":material/delete:"); st.rerun()
    if edit:
        txt = st.text_area("Edited reply", value=r.draft_reply, height=180, key=f"txt_{r.id}", label_visibility="collapsed")
        if st.button("Save edit and approve", key=f"sv_{r.id}", type="primary"):
            add_review(id=r.id, action="edit", text=txt); flash(f"{r.id} edited and approved"); st.rerun()
    with st.expander("Correct the prediction"):
        f1, f2, f3 = st.columns([1.2, 1, 1.6])
        new_cat = f1.selectbox("Category", CAT_ORDER, index=CAT_ORDER.index(LABELS[r.pred_category]), key=f"cat_{r.id}")
        new_sent = f2.selectbox("Sentiment", ["negative", "neutral", "positive"], index=["negative", "neutral", "positive"].index(r.pred_sentiment), key=f"sen_{r.id}")
        why = f3.text_input("Reason for this edit", key=f"why_{r.id}", placeholder="optional")
        if st.button("Save correction", key=f"cor_{r.id}"):
            inv = {v: k for k, v in LABELS.items()}
            if inv[new_cat] != r.pred_category:
                add_review(id=r.id, action="correct", field="category", old=r.pred_category, new=inv[new_cat], reason=why)
            if new_sent != r.pred_sentiment:
                add_review(id=r.id, action="correct", field="sentiment", old=r.pred_sentiment, new=new_sent, reason=why)
            flash(f"Correction logged for {r.id}", ":material/edit_note:"); st.rerun()
        h('<div class="note">Corrections are logged for the next training run. They do not change the live model.</div>')
    rv = load_reviews()
    mine = rv[rv.id == r.id].sort_values("at", ascending=False) if len(rv) else rv
    if len(mine):
        lines = ""
        for x in mine.itertuples():
            if x.action == "correct":
                what = f"changed {x.field}: {LABELS.get(x.old, x.old)} → {LABELS.get(x.new, x.new)}"
            else:
                what = {"approve": "approved the draft", "discard": "discarded the draft", "edit": "edited and approved the draft"}.get(x.action, x.action)
            rs = f' · "{x.reason}"' if isinstance(x.reason, str) and x.reason else ""
            lines += f'<div><span class="when">{x.at[5:16].replace("T", " ")}</span><b>{x.reviewer}</b> {what}{rs}</div>'
        h(f'<div class="audit" style="margin-top:6px">{lines}</div>')


